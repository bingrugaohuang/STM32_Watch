#ifndef OLED_COMMON_H
#define OLED_COMMON_H

/* ================================================================
 *  OLED 驱动公共定义
 * 该头文件包含 OLED 驱动的全局常量、类型定义和全局变量声明，
 * ================================================================ */

 /* ================================================================
  *  OLED I2C 通信相关定义
  * ================================================================ */
#define OLED_I2C_ADDR  0x3C // OLED I2C 地址（7 位地址，左移 1 位后最低位为 R/W 位）
#define OLED_CTRL_CMD  0x00 // OLED 控制字节：表示后续字节为命令
#define OLED_CTRL_DATA 0x40 // OLED 控制字节：表示后续字节为数据

/* ================================================================
 *  字体大小定义（与字库数据 OLED_F6x8/OLED_F8x16/OLED_F12x24 对应）
 * ================================================================ */
#define OLED_8X16      8   /* 8 像素宽，16 像素高 */
#define OLED_6X8       6   /* 6 像素宽，8 像素高  */
#define OLED_12X24     12  /* 12 像素宽，24 像素高 */

/* ---- 填充标志 ---- */
#define OLED_UNFILLED  0   /* 不填充（仅边框） */
#define OLED_FILLED    1   /* 填充内部        */

#endif /* OLED_COMMON_H */